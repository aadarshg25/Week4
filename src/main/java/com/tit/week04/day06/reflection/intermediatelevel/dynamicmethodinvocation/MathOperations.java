package com.tit.week04.day06.reflection.intermediatelevel.dynamicmethodinvocation;

class MathOperations {
    public int add(int a, int b) {
        return a + b;
    }

    public int subtract(int a, int b) {
        return a - b;
    }

    public int multiply(int a, int b) {
        return a * b;
    }
}